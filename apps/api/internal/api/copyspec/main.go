// Command copyspec copies the contract into the api package, so the server
// can embed it for request validation (ADR 0012). go:embed cannot reach
// files outside the module, and Vercel builds from apps/api only. Run by
// `go generate`; CI fails if the copy is stale.
package main

import (
	"bytes"
	"fmt"
	"os"
)

const header = "# Code generated by copyspec from openapi/openapi.yaml. DO NOT EDIT.\n"

func main() {
	if len(os.Args) != 3 {
		fmt.Fprintln(os.Stderr, "usage: copyspec <source> <destination>")
		os.Exit(2)
	}
	src, err := os.ReadFile(os.Args[1]) //nolint:gosec // G703: paths come from the go:generate line, not from users
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	// LF everywhere, so the copy is the same on Windows and in CI.
	src = bytes.ReplaceAll(src, []byte("\r\n"), []byte("\n"))
	if err := os.WriteFile(os.Args[2], append([]byte(header), src...), 0o644); err != nil { //nolint:gosec // G306: a source file, meant to be readable
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
